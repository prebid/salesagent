#!/usr/bin/env python3
"""Generate docs/development/admin-ui-routes.md from the Admin UI's own URL map.

The page lists every route the Flask admin application serves, with the access
check and the audit operation its view function declares. Both come from the
code: the URL map of `create_app()`, and the decorators on each view function.

Usage:
    uv run python scripts/generate_admin_route_reference.py           # rewrite the page
    uv run python scripts/generate_admin_route_reference.py --check   # exit 1 when the page is stale
"""

from __future__ import annotations

import argparse
import ast
import inspect
import sys
from collections import defaultdict
from collections.abc import Callable
from pathlib import Path
from typing import Any, NamedTuple

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "development" / "admin-ui-routes.md"

# The decorators that decide who reaches a view, most specific first.
ACCESS_DECORATORS = (
    "require_tenant_access",
    "require_auth",
    "require_sync_api_key",
    "require_tenant_management_api_key",
)

HEADER = """\
# Admin UI route reference

<!-- Generated by scripts/generate_admin_route_reference.py. Do not edit by hand. -->

This page lists every route the Flask admin application serves. A script generates it from
the URL map of `create_app()` and from the decorators on each view function. To regenerate
the page after you add, move, or remove a route, run the following command:

```bash
uv run python scripts/generate_admin_route_reference.py
```

The paths are relative to the admin application. A deployment serves the application under
`/admin` and at the root, as [Admin UI architecture](admin-ui-architecture.md) explains.

Each table has the following columns:

- **Access check** is the decorator that decides who reaches the view. `role=UserRole.ADMIN`
  marks a route that only a tenant admin or a super admin reaches. `none` means the view
  function carries no access decorator. Such a view is public, or it checks the session in
  its own body. [Admin UI authentication and permissions](admin-ui-authentication.md)
  explains each check.
- **Audit operation** is the name the view passes to `log_admin_action`. `-` means the view
  writes no audit log row through that decorator.
- **View** is the Flask endpoint name, the value `url_for` takes.
"""


class Route(NamedTuple):
    path: str
    methods: str
    endpoint: str
    access: str
    audit: str


def _decorator_text(node: ast.expr) -> str:
    return ast.unparse(node).replace("\n", " ")


def _decorators(view: Callable[..., Any], trees: dict[str, ast.Module]) -> list[str]:
    """The decorator expressions on a view function, read from its source file."""
    inner = inspect.unwrap(view)
    code = inner.__code__
    if code.co_filename not in trees:
        trees[code.co_filename] = ast.parse(Path(code.co_filename).read_text())
    for node in ast.walk(trees[code.co_filename]):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == inner.__name__:
            first_line = min([node.lineno, *(d.lineno for d in node.decorator_list)])
            if first_line == code.co_firstlineno:
                return [_decorator_text(d) for d in node.decorator_list]
    return []


def _access(decorators: list[str]) -> str:
    for name in ACCESS_DECORATORS:
        for text in decorators:
            if text == name or text.startswith(f"{name}("):
                return f"`{text}`"
    return "none"


def _audit(decorators: list[str]) -> str:
    for text in decorators:
        if text.startswith("log_admin_action("):
            call = ast.parse(text, mode="eval").body
            if isinstance(call, ast.Call) and call.args and isinstance(call.args[0], ast.Constant):
                return f"`{call.args[0].value}`"
    return "-"


def collect_routes() -> dict[str, list[Route]]:
    """Every route of the admin application, grouped by the source file of its view."""
    sys.path.insert(0, str(ROOT))
    from src.admin.app import create_app

    app = create_app()
    trees: dict[str, ast.Module] = {}
    groups: dict[str, list[Route]] = defaultdict(list)
    for rule in app.url_map.iter_rules():
        view = app.view_functions[rule.endpoint]
        source = Path(inspect.unwrap(view).__code__.co_filename)
        group = str(source.relative_to(ROOT)) if source.is_relative_to(ROOT / "src") else "Flask"
        decorators = _decorators(view, trees) if group != "Flask" else []
        methods = ", ".join(sorted((rule.methods or set()) - {"HEAD", "OPTIONS"}))
        groups[group].append(Route(str(rule), methods, rule.endpoint, _access(decorators), _audit(decorators)))
    return groups


def render() -> str:
    groups = collect_routes()
    lines = [HEADER]
    for group in sorted(groups):
        lines += [
            f"## `{group}`" if group != "Flask" else "## Flask built-in",
            "",
            "| Path | Methods | Access check | Audit operation | View |",
            "|---|---|---|---|---|",
        ]
        for route in sorted(groups[group]):
            lines.append(f"| `{route.path}` | {route.methods} | {route.access} | {route.audit} | `{route.endpoint}` |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when the page is stale")
    args = parser.parse_args()

    page = render()
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != page:
            print(f"{PAGE.relative_to(ROOT)} is stale. Run: uv run python {Path(__file__).relative_to(ROOT)}")
            return 1
        return 0
    PAGE.write_text(page)
    print(f"Wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
