"""Integration tests for A2A response spec compliance.

This test suite validates that:
1. A2A responses carry only spec-defined fields — no invented key like ``success``
2. Response data is identical between MCP and A2A protocols

``message`` is NOT such an invented key and is no longer asserted absent. The pin
declares it on the protocol envelope (``core/protocol-envelope.json``: "Human-readable
summary of the task result ... Generated by the protocol layer"), every response model
inherits ``adcp.types.ProtocolEnvelope``, and the implementation fills it — so it is
spec-defined payload that reaches MCP, A2A and REST alike through the one serializer,
``src/core/tools/_wire.py::to_wire``. The assertions that once demanded ``"message" not
in response_dict`` stated the opposite of the pinned envelope.

``success`` IS such an invented key, and is still asserted absent everywhere it used to
be asserted absent — plus in the places A2A used to write it. A2A derived it from
``errors`` and stamped it into every body; the pinned 3.1 tree declares a ``success``
property on three response schemas, none of them one of our fourteen tools.

The 23 curated ``__str__`` methods these tests read the buyer-facing sentence from are
deleted. The implementations write that sentence to ``message`` now, so it is graded on
the field, on a real dispatch — here for get_media_buys, and on the ``on_message_send``
pipeline output in ``tests/integration/test_a2a_skill_invocation.py``.

REPLACED, and the replacement is now COMPLETE: test_a2a_response_message_fields.py is
DELETED, not merely superseded. This header claimed to replace it while the file went on
living in the tree, and it was still being repaired -- a carrier fix landed in it during
the ecfdd7771 cleanup -- so someone was paying maintenance on tests this file had already
declared obsolete. Both of its premises were gone: ``_stamp_a2a_protocol_fields``, the
transport-side ``message`` stamp it was written against, survives nowhere in ``src/``, and
``to_wire`` is ``model_dump(mode="json")`` and nothing else, so asserting that the message
a caller set is the message that comes back asserts pydantic. Do not restore it from
history; the obligations it named are graded here and in
``tests/integration/test_a2a_skill_invocation.py`` on a real dispatch.
"""

