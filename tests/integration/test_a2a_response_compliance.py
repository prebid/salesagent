@pytest.mark.integration
class TestGetMediaBuysProtocolMessage:
    """``get_media_buys`` must not put a Python repr on the protocol ``message``.

    The defect this pins used to be a transport one: ``GetMediaBuysResponse`` carried no
    curated ``__str__``, so ``str(response)`` was a 316-character pydantic repr containing
    the literal ``message=None``, and both transports handed a buyer exactly that —
    ``_stamp_a2a_protocol_fields`` wrote ``str(response)`` into the A2A body, and
    ``mcp_result`` fell back to ``str(response)`` for ``ToolResult.content``.

    Both fallbacks are gone. ``message`` is a declared envelope field, the implementation
    fills it (``src/core/tools/media_buy_list.py``), and ``to_wire`` carries it out
    unchanged — so the repr can only come back by the implementation putting one there.
    That is what is graded, on the wire, for the three branches of the count form:
    zero, one, many.

    Graded through a real A2A dispatch rather than by calling the producing function:
    ``message`` reaching the body is exactly what the deleted stamp used to be
    responsible for, so a unit call on the impl would no longer see the step that
    regressed. One transport is enough because ``to_wire`` is the only body producer and
    ``test_harness_wire_response.py`` pins that the three transports agree byte for byte.
    """

    @pytest.mark.parametrize(
        ("count", "expected_message"),
        [
            (0, "No media buys found."),
            (1, "Found 1 media buy."),
            (3, "Found 3 media buys."),
        ],
    )
    def test_stamped_protocol_message_is_curated_text(self, count, expected_message, integration_db):
        """Sync on purpose: ``call_via`` bridges to ``asyncio.run()`` internally, so an
        ``async def`` test would nest event loops and swallow the RuntimeError.
        """
        from datetime import date

        from tests.factories import MediaBuyFactory, PrincipalFactory, TenantFactory
        from tests.harness.media_buy_list import MediaBuyListEnv
        from tests.harness.transport import Transport

        with MediaBuyListEnv(tenant_id="t-msg", principal_id="p-msg") as env:
            tenant = TenantFactory(tenant_id="t-msg")
            principal = PrincipalFactory(tenant=tenant, principal_id="p-msg")
            for i in range(count):
                MediaBuyFactory(
                    tenant=tenant,
                    principal=principal,
                    media_buy_id=f"mb-msg-{i}",
                    status="active",
                    start_date=date(2026, 1, 1),
                    end_date=date(2026, 12, 31),
                )
            env._commit_factory_data()
            result = env.call_via(Transport.A2A)

        body = result.wire_response
        # The row count is asserted alongside the sentence: without it a message reading
        # "No media buys found." passes on a query that silently returned nothing, which
        # is the failure the singular/plural form is least able to distinguish.
        assert len(body["media_buys"]) == count, f"expected {count} media buys on the wire, got {body['media_buys']!r}"
        assert body["message"] == expected_message


@pytest.mark.integration
class TestMCPAndA2AResponseParity:
    """Test that MCP and A2A return identical response data."""

    def test_all_response_types_declare_the_message_field(self):
        """Every AdCP response type declares ``message``, the field both protocols read.

        This replaces a ``hasattr(cls, "__str__")`` check that could not fail — every
        Python object has ``__str__`` — and whose 23 curated overrides are deleted
        anyway. The parity this class is about now rests on the field: MCP reads
        ``response.message`` for ``ToolResult.content`` and both protocols carry the
        same ``to_wire`` body, so a response type that declared no ``message`` would
        give a buyer an empty summary on one protocol and nothing on the other.
        """
        response_types = [
            CreateMediaBuySuccess,
            UpdateMediaBuySuccess,
            GetMediaBuyDeliveryResponse,
            GetProductsResponse,
            ListCreativeFormatsResponse,
            ListCreativesResponse,
            SyncCreativesResponse,
        ]

        for response_cls in response_types:
            assert "message" in response_cls.model_fields, (
                f"{response_cls.__name__} declares no `message` — it is outside the protocol "
                "envelope, so neither MCP nor A2A can give a buyer a summary of it"
            )


@pytest.mark.integration
class TestA2AResponseRegressionPrevention:
    """Prevent regressions: ensure we never add non-spec fields back."""

    def test_no_protocol_fields_in_response_data(self):
        """Ensure protocol metadata is separate from response data."""
        # Protocol fields like 'status', 'task_id', 'context_id' should be
        # in the protocol wrapper (Task), not in the response data (Artifact.parts.data)

        response = GetProductsResponse(products=[])
        response_dict = response.model_dump()

        # These are protocol-envelope fields (spec-defined on the WIRE
        # envelope's Protocol Envelope branch — see
        # tests/helpers/adcp_schema_validator.py — and populated by the protocol
        # layer at the transport boundary), correctly absent from the
        # Pydantic response MODEL itself.
        protocol_fields = {"task_id", "context_id"}  # status is actually in some AdCP responses

        violations = protocol_fields & set(response_dict.keys())
        assert violations == set(), f"Response data contains protocol fields: {violations}"


@pytest.mark.integration
class TestA2AErrorsSurviveToTheWireWithoutSuccess:
    """A2A no longer writes ``success``, and ``errors`` is what a buyer reads instead.

    This class used to pin the opposite half of the same mechanism:
    ``_stamp_a2a_protocol_fields`` DERIVED ``success`` from ``errors`` and wrote it into
    every payload, and the derivation was the thing at risk (PR #1868 found three call
    sites duplicating the stamp, one of them forcing ``success=True`` regardless of
    ``errors``).

    The stamp is deleted rather than fixed. Measured across the pinned 3.1 tree, three
    response schemas declare a ``success`` property and none of them is one of our
    fourteen tools, so A2A was writing a key AdCP does not define into every buyer's
    payload — and it had no consumers, because a buyer derives the same fact from
    ``errors``.

    That last clause is the only load this class still carries, and it is worth carrying:
    "the buyer can derive it from ``errors``" is false if ``errors`` does not reach the
    buyer. So the same dispatch now asserts the two things that replaced the derivation —
    ``errors`` arrives intact, and ``success`` does not arrive at all.
    """

    def test_get_products_populated_errors_reach_the_wire(self, integration_db):
        """Sync on purpose: ``call_a2a``/``call_via`` bridge to ``asyncio.run()``
        internally (see ``ProductEnv.call_impl``'s docstring on the same bridge) —
        an ``async def`` test would nest event loops and silently swallow the
        resulting RuntimeError.
        """
        from unittest.mock import AsyncMock

        from src.core.schemas import Error, GetProductsResponse
        from tests.bdd.steps._outcome_helpers import wire_dict
        from tests.bdd.steps.generic._dispatch import dispatch_request
        from tests.factories import PrincipalFactory, TenantFactory
        from tests.harness.product import ProductEnv
        from tests.harness.transport import Transport

        with ProductEnv(tenant_id="a2a-success-errors-test", principal_id="test_principal") as env:
            tenant = TenantFactory(tenant_id="a2a-success-errors-test")
            PrincipalFactory(tenant=tenant, principal_id="test_principal")

            # get_products has no production code path that populates
            # non-fatal errors[] today (unlike CreateMediaBuySuccess's
            # property_list_filtering advisory) — stub the tool boundary
            # A2A dispatches through, the same seam the transport is
            # contractually bound to (Pattern #5), so the serialization the
            # transport owns is graded independent of whether any business
            # path currently exercises it.
            errored_response = GetProductsResponse(
                products=[],
                errors=[Error(code="UNSUPPORTED_FEATURE", message="property_list_filtering unavailable")],
            )

            # Substituted at the REGISTRY ROW, which is what the A2A handler dispatches
            # through; a module attribute is not consulted by any transport.
            with registry_impl("get_products", AsyncMock(return_value=errored_response)):
                ctx: dict = {"env": env, "transport": Transport.A2A}
                dispatch_request(ctx, brief="display ads")

            body = wire_dict(ctx)

        assert "success" not in body, f"A2A stamped `success` back onto the payload: {body!r}"
        assert [e["code"] for e in body["errors"]] == ["UNSUPPORTED_FEATURE"], (
            f"the errors the buyer derives failure from did not reach the wire: {body!r}"
        )
